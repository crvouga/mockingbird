/**
 * Regenerates src/errors.generated.ts from MinIO's `cmd/api-errors.go`, the oracle's own error
 * table (code, message, HTTP status). Usage: bun scripts/minio-errors.ts <path to minio checkout>
 */
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const root = process.argv[2]
if (!root) throw new Error("usage: bun scripts/minio-errors.ts <minio checkout>")
const source = readFileSync(join(root, "cmd/api-errors.go"), "utf8")
const statuses: Record<string, number> = {
  StatusBadRequest: 400,
  StatusUnauthorized: 401,
  StatusForbidden: 403,
  StatusNotFound: 404,
  StatusMethodNotAllowed: 405,
  StatusNotAcceptable: 406,
  StatusConflict: 409,
  StatusGone: 410,
  StatusLengthRequired: 411,
  StatusPreconditionFailed: 412,
  StatusRequestEntityTooLarge: 413,
  StatusRequestURITooLong: 414,
  StatusUnsupportedMediaType: 415,
  StatusRequestedRangeNotSatisfiable: 416,
  StatusExpectationFailed: 417,
  StatusTooManyRequests: 429,
  StatusRequestHeaderFieldsTooLarge: 431,
  StatusInternalServerError: 500,
  StatusNotImplemented: 501,
  StatusBadGateway: 502,
  StatusServiceUnavailable: 503,
  StatusGatewayTimeout: 504,
  StatusInsufficientStorage: 507,
  StatusNotModified: 304,
  StatusPaymentRequired: 402,
  StatusRequestTimeout: 408,
  StatusUnprocessableEntity: 422,
  StatusOK: 200,
  StatusNoContent: 204,
  StatusPartialContent: 206,
  StatusMisdirectedRequest: 421,
  StatusTeapot: 418,
  StatusUpgradeRequired: 426,
  StatusPreconditionRequired: 428,
  StatusUnavailableForLegalReasons: 451,
  StatusLocked: 423,
  StatusFailedDependency: 424,
  StatusTooEarly: 425,
}
const entries: [string, string, string, number][] = []
const pattern =
  /\t(Err\w+): \{\s*Code:\s*("(?:[^"\\]|\\.)*"|`[^`]*`),\s*Description:\s*("(?:[^"\\]|\\.)*"(?:\s*\+\s*"(?:[^"\\]|\\.)*")*|`[^`]*`|fmt\.Sprintf\([^)]*\)),\s*HTTPStatusCode:\s*(?:http\.(\w+)|(\d+)),?\s*\}/g
const literal = (value: string) => {
  if (value.startsWith("`")) return value.slice(1, -1)
  if (value.startsWith("fmt.Sprintf(")) {
    const inner = /fmt\.Sprintf\(("(?:[^"\\]|\\.)*")/.exec(value)?.[1] ?? '""'
    return JSON.parse(inner) as string
  }
  return value
    .split(/\s*\+\s*/)
    .map((piece) => JSON.parse(piece) as string)
    .join("")
}
for (const match of source.matchAll(pattern)) {
  const [, name, code, description, statusName, statusNumber] = match
  const status = statusName ? statuses[statusName] : Number(statusNumber)
  if (!status) throw new Error(`unknown status ${statusName} for ${name}`)
  entries.push([name as string, literal(code as string), literal(description as string), status])
}
const lines = entries.map(
  ([name, code, message, status]) =>
    `  ${name.slice(3)}: [${JSON.stringify(code)}, ${JSON.stringify(message)}, ${status}],`,
)
writeFileSync(
  join(import.meta.dir, "../src/errors.generated.ts"),
  `// Generated by scripts/minio-errors.ts from MinIO's cmd/api-errors.go; do not edit.
/** MinIO's error table: name → [S3 code, message, HTTP status]. */
export const MINIO_ERRORS = {
${lines.join("\n")}
} as const satisfies Record<string, readonly [string, string, number]>
export type ErrorName = keyof typeof MINIO_ERRORS
`,
)
console.log(`${entries.length} errors`)
