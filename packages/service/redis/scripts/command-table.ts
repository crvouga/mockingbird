/**
 * Regenerates `src/command-table.ts`: the `COMMAND INFO` / `COMMAND DOCS` metadata of every command
 * the emulator implements, captured from a real Redis. Run it after adding a command:
 *
 *   bun scripts/command-table.ts [redis://host:port]
 *
 * Without a URL it starts a throwaway local `redis-server` on a free port. A command counts as
 * implemented when the emulator answers it with anything other than "unknown command".
 */

import { spawn } from "node:child_process"
import { writeFileSync } from "node:fs"
import { createConnection, createServer } from "node:net"
import { Redis } from "ioredis"
import { createRedis } from "../src/index.ts"

const freePort = () =>
  new Promise<number>((resolve, reject) => {
    const probe = createServer()
    probe.once("error", reject)
    probe.listen(0, "127.0.0.1", () => {
      const address = probe.address()
      probe.close(() => resolve(typeof address === "object" && address ? address.port : 0))
    })
  })

const accepts = (port: number) =>
  new Promise<boolean>((resolve) => {
    const socket = createConnection({ host: "127.0.0.1", port })
    socket.once("connect", () => socket.end(() => resolve(true)))
    socket.once("error", () => resolve(false))
  })

let url = process.argv[2]
let child: ReturnType<typeof spawn> | undefined
if (!url) {
  const port = await freePort()
  child = spawn("redis-server", ["--port", String(port), "--save", "", "--appendonly", "no"], {
    stdio: "ignore",
  })
  url = `redis://127.0.0.1:${port}`
  for (let attempt = 0; attempt < 100 && !(await accepts(port)); attempt++)
    await new Promise((resolve) => setTimeout(resolve, 50))
}

const redis = new Redis(url, { lazyConnect: true })
await redis.connect()
try {
  const infos = (await redis.call("COMMAND", "INFO")) as unknown[][]
  const docs = (await redis.call("COMMAND", "DOCS")) as unknown[]
  const docOf = new Map<string, Record<string, string>>()
  for (let i = 0; i < docs.length; i += 2) {
    const fields = docs[i + 1] as unknown[]
    const doc: Record<string, string> = {}
    for (let j = 0; j < fields.length; j += 2)
      if (typeof fields[j + 1] === "string") doc[String(fields[j])] = String(fields[j + 1])
    docOf.set(String(docs[i]), doc)
  }
  const emulator = createRedis()
  const client = emulator.client()
  const rows: unknown[][] = []
  for (const info of infos.sort((a, b) => String(a[0]).localeCompare(String(b[0])))) {
    const name = String(info[0])
    if (name.includes("|")) continue
    const reply = await client.raw(name)
    if (reply.t === "error" && reply.v.startsWith("ERR unknown command")) continue
    const doc = docOf.get(name) ?? {}
    rows.push([
      name,
      info[1],
      (info[2] as string[]).join(" "),
      info[3],
      info[4],
      info[5],
      (info[6] as string[]).join(" "),
      doc.summary ?? "",
      doc.since ?? "",
      doc.group ?? "",
      doc.complexity ?? "",
    ])
  }
  emulator.close()
  const body = rows.map((row) => `  ${JSON.stringify(row.join("\t"))},`).join("\n")
  const file = new URL("../src/command-table.ts", import.meta.url)
  writeFileSync(
    file,
    `// Generated by \`bun scripts/command-table.ts\` from redis-server ${await version(redis)}. Do not edit by hand.
/** name, arity, flags, first key, last key, key step, ACL categories, summary, since, group, complexity */
export type CommandRow = readonly [
  string,
  number,
  string,
  number,
  number,
  number,
  string,
  string,
  string,
  string,
  string,
]

const ROWS = [
${body}
]

export const COMMAND_TABLE: readonly CommandRow[] = ROWS.map((row) => {
  const [name = "", arity, flags = "", first, last, step, categories = "", ...docs] = row.split("\\t")
  const [summary = "", since = "", group = "", complexity = ""] = docs
  return [name, Number(arity), flags, Number(first), Number(last), Number(step), categories, summary, since, group, complexity]
})
`,
  )
  console.log(`wrote ${rows.length} commands`)
} finally {
  redis.disconnect()
  child?.kill()
}

async function version(client: Redis): Promise<string> {
  const info = await client.info("server")
  return /redis_version:(\S+)/.exec(info)?.[1] ?? "unknown"
}
