/**
 * Declarative catalog overlays: lab tests derived from ones the catalog already holds, with no
 * network access. `createRuntime({ catalogOverlays: [...] })` adds them to every namespace
 * after the catalog (default or corpus) is loaded, again on every `reset()`.
 */
import type { ExpectedResult, LabTestRecord } from "./catalog.js"
import type { JunctionState } from "./state.js"

export type CatalogOverlay = {
  /** The lab test to clone, by id or slug. It must be in the catalog the namespace boots with. */
  from: string
  /** Id of the new lab test (a UUID, as `create_order` expects). */
  id: string
  name?: string
  slug?: string
  /**
   * Move the clone to a lab: the slug of a lab the catalog lists, or a lab record
   * (`{ id, slug, name, ... }`), which is added to `GET /v3/lab_tests/labs` when new.
   * The clone's markers and expected results take that lab's id.
   */
  lab?: string | Record<string, unknown>
  /** Drop the ask-on-order questions from every marker of the clone. */
  stripAoe?: boolean
  /** Set `auto_generated` on the clone. Default: as the source. */
  autoGenerated?: boolean
  method?: string
  /** Dollars. */
  price?: number
  status?: string
}

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

/** Check overlays without a catalog: shape, UUIDs, and clashes between them. */
export const validateCatalogOverlays = (overlays: readonly CatalogOverlay[]): void => {
  const ids = new Set<string>()
  for (const [index, overlay] of overlays.entries()) {
    const at = `catalogOverlays[${index}]`
    if (typeof overlay.from !== "string" || overlay.from === "")
      throw new TypeError(`${at}.from: expected the id or slug of a lab test`)
    if (typeof overlay.id !== "string" || !UUID.test(overlay.id))
      throw new TypeError(`${at}.id: expected a UUID`)
    if (ids.has(overlay.id)) throw new TypeError(`${at}.id: ${overlay.id} is used twice`)
    ids.add(overlay.id)
    if (overlay.price !== undefined && !(Number.isFinite(overlay.price) && overlay.price >= 0))
      throw new TypeError(`${at}.price: expected dollars as a non-negative number`)
  }
}

/** Add each overlay's lab test, in order, so a later overlay can clone an earlier one. */
export const applyCatalogOverlays = (
  state: JunctionState,
  overlays: readonly CatalogOverlay[],
): void => {
  for (const [index, overlay] of overlays.entries()) {
    const at = `catalogOverlays[${index}]`
    const tests = state.listLabTests()
    const source = tests.find((test) => test.id === overlay.from || test.slug === overlay.from)
    if (!source) throw new Error(`${at}.from: no lab test with id or slug ${overlay.from}`)
    if (tests.some((test) => test.id === overlay.id))
      throw new Error(`${at}.id: lab test ${overlay.id} already exists in the catalog`)
    const clone = structuredClone(source) as LabTestRecord
    clone.id = overlay.id
    if (overlay.name !== undefined) clone.name = overlay.name
    clone.slug =
      overlay.slug ??
      (overlay.name === undefined ? `${source.slug}_${index + 1}` : slugOf(overlay.name))
    if (overlay.method !== undefined) clone.method = overlay.method
    if (overlay.price !== undefined) clone.price = overlay.price
    if (overlay.status !== undefined) {
      clone.status = overlay.status
      clone.is_active = overlay.status === "active"
    }
    if (overlay.autoGenerated !== undefined) clone.auto_generated = overlay.autoGenerated
    const expected: ExpectedResult[] = structuredClone(state.expectedResultsFor(source.id))
    if (overlay.lab !== undefined) {
      const lab = labFor(state, overlay.lab, at)
      clone.lab = structuredClone(lab)
      const labId = typeof lab.id === "number" ? lab.id : null
      for (const marker of clone.markers ?? []) marker.lab_id = labId
      for (const result of expected) result.lab_id = labId
    }
    if (overlay.stripAoe === true) for (const marker of clone.markers ?? []) marker.aoe = null
    state.upsertLabTest(clone, expected)
  }
}

const slugOf = (name: string): string =>
  name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")

const labFor = (
  state: JunctionState,
  lab: string | Record<string, unknown>,
  at: string,
): Record<string, unknown> => {
  const labs = state.listLabs()
  if (typeof lab === "string") {
    const found = labs.find((entry) => entry.slug === lab)
    if (!found) throw new Error(`${at}.lab: the catalog lists no lab with slug ${lab}`)
    return found
  }
  const known = labs.find((entry) => state.labKeyOf(entry) === state.labKeyOf(lab))
  if (known) return known
  state.labs.insert(state.labKeyOf(lab), structuredClone(lab))
  return lab
}
