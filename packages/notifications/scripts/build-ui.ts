/**
 * Bundle the browser UI (src/ui/browser.ts) into src/generated/browser.ts as a string, so the
 * harness serves it from memory under Node, Bun and the published bundle alike.
 *
 *   bun scripts/build-ui.ts
 */
import { mkdirSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { build } from "esbuild"

const root = join(import.meta.dir, "..")
const result = await build({
  entryPoints: [join(root, "src/ui/browser.ts")],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: true,
  write: false,
})
const code = result.outputFiles?.[0]?.text
if (!code) throw new Error("UI build produced no bundle")
mkdirSync(join(root, "src/generated"), { recursive: true })
writeFileSync(
  join(root, "src/generated/browser.ts"),
  `// Generated by scripts/build-ui.ts from src/ui/browser.ts. Do not edit.\nexport const BROWSER_JS: string = ${JSON.stringify(code)}\n`,
)
console.log(`build-ui: ${(code.length / 1024).toFixed(1)} KiB → src/generated/browser.ts`)
