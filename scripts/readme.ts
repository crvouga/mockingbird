/**
 * Generates the repo README.md: the overview of Mockingbird. The catalog of emulators, including
 * each service's parity, lives on the docs site and in llms.txt. Every word comes from the
 * shared copy (sites/docs/src/lib/content.ts), the published packages' license, and the guides
 * in docs/. Edit those, never README.md.
 *
 *   bun run readme:sync     rewrite README.md
 *   bun run check:readme    fail if README.md is stale (CI)
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import {
  ADMIN_CONTROLS,
  AGENTS,
  CONTRACT,
  FEATURES,
  GUIDE_CHILDREN,
  HEADLINE,
  IDENTITY,
  MARK_REPO_PATH,
  PITCH,
  QUICK_START,
  RISK_DISCLAIMER,
} from "../sites/docs/src/lib/content.ts"
import { guideInfo, sortGuides } from "../sites/docs/src/lib/guides.ts"
import { discoverPackages, REPO, root } from "./release/lib.ts"

const OUT = join(root, "README.md")

for (const rel of [MARK_REPO_PATH]) {
  if (!existsSync(join(root, rel))) {
    console.error(`::error::missing identity file: ${rel}`)
    process.exit(1)
  }
}

interface Manifest {
  license?: string
}

const licenses = new Set(
  discoverPackages()
    .filter((p) => p.isPublic)
    .map((p) => (JSON.parse(readFileSync(p.manifestPath, "utf8")) as Manifest).license ?? ""),
)
if (licenses.size !== 1) {
  console.error(
    `::error::published packages disagree on their license: ${[...licenses].join(", ")}`,
  )
  process.exit(1)
}
const [license = "MIT"] = licenses

const guides = sortGuides(
  readdirSync(join(root, "docs"))
    .filter((f) => f.endsWith(".md"))
    .map((f) =>
      guideInfo({ file: f.slice(0, -3), markdown: readFileSync(join(root, "docs", f), "utf8") }),
    ),
)

/** The admin controls guide's pages, one per control, in the order the docs site shows them. */
const controlPages = GUIDE_CHILDREN.ADMIN_CONTROLS.map((name) => {
  const path = `${ADMIN_CONTROLS.pages}/${name}.md`
  return {
    name,
    path,
    ...guideInfo({ file: name, markdown: readFileSync(join(root, path), "utf8") }),
  }
})
const controlPath = (name: string) => `${ADMIN_CONTROLS.pages}/${name}.md`

const cell = (s: string) => s.replace(/\|/g, "\\|")
const badge = (label: string, message: string | number, color: string) =>
  `https://img.shields.io/badge/${encodeURIComponent(label.replace(/-/g, "--").replace(/ /g, "_"))}-${encodeURIComponent(String(message))}-${color}`

const catalog = `${IDENTITY.docs}/services`

const body = [
  "<!-- Generated by scripts/readme.ts from sites/docs/src/lib/content.ts, the published packages' license, and docs/*.md. Edit those, then run `bun run readme:sync`. CI fails when this file is stale. The catalog of emulators lives on the docs site. -->",
  "",
  '<div align="center">',
  "",
  `<h1>${IDENTITY.icon} ${IDENTITY.name}</h1>`,
  "",
  `**${HEADLINE.lead} ${HEADLINE.accent}**`,
  "",
  IDENTITY.note,
  "",
  [
    `[![CI](https://github.com/${REPO}/actions/workflows/pr.yml/badge.svg)](https://github.com/${REPO}/actions/workflows/pr.yml)`,
    `[![License](${badge("license", license, "2563eb")})](#license)`,
  ].join(" "),
  "",
  `[Quick start](#quick-start) · [Why](docs/WHY.md) · [Design](docs/DESIGN.md) · [Guides](#guides) · [Catalog](${catalog}) · [llms.txt](llms.txt)`,
  "",
  "</div>",
  "",
  ...(RISK_DISCLAIMER.enabled ? [`> ⚠️ ${RISK_DISCLAIMER.text}`, ""] : []),
  PITCH,
  "",
  `Each emulator is its own npm package. The catalog — names, parity, and what each one covers — is on the [docs site](${catalog}).`,
  "",
  "## Quick start",
  "",
  "```bash",
  `npm install -D ${QUICK_START.packages.join(" ")}`,
  "```",
  "",
  `Build a checkout with a PostgreSQL product catalog and a Stripe payment. Save these three files together, then run \`bun client.ts\` (or \`npx tsx client.ts\` with Node). The API calls the \`${QUICK_START.sdk}\` SDK your application already depends on; in an empty project, install it first.`,
  "",
  ...QUICK_START.steps.flatMap((step) => [
    `### ${step.title} · \`${step.file}\``,
    "",
    step.description,
    "",
    "```ts",
    step.code,
    "```",
    "",
  ]),
  `Every package is self-contained ESM with TypeScript types. Every emulator is isomorphic and runs in Node >= 22, Bun >= 1.2, browsers, and Workers. Browse every emulator, with a live playground, on the [docs site](${catalog}).`,
  "",
  "## Why Mockingbird",
  "",
  ...FEATURES.map((f) => `- **${f.title}.** ${f.body}`),
  "",
  "The full rationale, and when not to use it: [docs/WHY.md](docs/WHY.md).",
  "",
  "## Admin controls",
  "",
  `**${ADMIN_CONTROLS.title}**`,
  "",
  ADMIN_CONTROLS.intro,
  "",
  ...ADMIN_CONTROLS.controls.map(
    (control) => `- **[${control.title}](${controlPath(control.page)}).** ${control.body}`,
  ),
  "",
  ...ADMIN_CONTROLS.carriers.flatMap((carrier) => [
    `${carrier.label}:`,
    "",
    `\`\`\`${carrier.lang}`,
    carrier.code,
    "```",
    "",
  ]),
  ADMIN_CONTROLS.determinism,
  "",
  `Start at [${ADMIN_CONTROLS.guide}](${ADMIN_CONTROLS.guide}). Each control has its own page, with its routes, body fields, headers, boot options and errors:`,
  "",
  "| Control | |",
  "| --- | --- |",
  ...controlPages.map((page) => `| [${cell(page.title)}](${page.path}) | ${cell(page.summary)} |`),
  "",
  "## One contract for every HTTP service",
  "",
  CONTRACT.intro,
  "",
  "```bash",
  CONTRACT.serve,
  "```",
  "",
  "| Surface | What it gives you |",
  "| --- | --- |",
  ...CONTRACT.rows.map(([surface, detail]) => `| ${cell(surface)} | ${cell(detail)} |`),
  "",
  "```json",
  CONTRACT.config,
  "```",
  "",
  CONTRACT.configNote,
  "",
  "## For coding agents",
  "",
  AGENTS,
  "",
  "## Contributing",
  "",
  "```bash",
  `git clone https://github.com/${REPO}.git && cd mockingbird`,
  "bun run setup   # install, build every package, create .env.local",
  "bun test",
  "```",
  "",
  "Building, testing and `bun run check` need no secrets and no accounts. Live parity against the real provider sandboxes runs on GitHub Actions with the repo's secrets, so anyone with write access runs it without holding a key: `bun run parity:remote -- <service>`. See [docs/DEVELOPMENT.md](docs/DEVELOPMENT.md) and [docs/SECRETS.md](docs/SECRETS.md).",
  "",
  "## Guides",
  "",
  "| Guide | |",
  "| --- | --- |",
  ...guides.map((g) => `| [${cell(g.title)}](docs/${g.file}.md) | ${cell(g.summary)} |`),
  "",
  "## License",
  "",
  `${license}.`,
  "",
].join("\n")

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : ""
  if (current !== body) {
    console.error(
      "::error::README.md is stale or was edited by hand — edit its sources, then run: bun run readme:sync",
    )
    process.exit(1)
  }
  console.log(`README.md: OK (${guides.length} guides)`)
} else {
  writeFileSync(OUT, body)
  console.log(`README.md: wrote ${guides.length} guides`)
}
