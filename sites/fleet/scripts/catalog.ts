/**
 * Generates the emulator catalog from every service package's `package.json`:
 * `src/generated/catalog.ts` (metadata plus one lazy `import()` per emulator) and this package's
 * workspace dependencies. `--check` fails when either is stale.
 *
 *   bun run catalog
 */
import { readdirSync } from "node:fs"
import { join } from "node:path"

const root = join(import.meta.dir, "..")
const services = join(root, "../../packages/service")
const check = process.argv.includes("--check")

/** Wire-protocol servers (PostgreSQL, Redis, SQLite sockets). The cloud serves one HTTP port. */
const NOT_HTTP = new Set(["postgres", "redis", "sqlite"])

type Manifest = {
  name: string
  description?: string
  exports?: Record<string, unknown>
  mockingbird?: {
    layer?: string
    category?: string
    displayName?: string
    vendor?: { website?: string; docs?: string }
  }
}

const entries: {
  target: string
  package: string
  displayName: string
  category: string
  description: string
  website?: string
  docs?: string
}[] = []

for (const directory of readdirSync(services).sort()) {
  const file = Bun.file(join(services, directory, "package.json"))
  if (!(await file.exists())) continue
  const manifest = (await file.json()) as Manifest
  if (manifest.mockingbird?.layer !== "service" || !manifest.exports?.["./server"]) continue
  if (NOT_HTTP.has(directory)) continue
  entries.push({
    target: directory,
    package: manifest.name,
    displayName: manifest.mockingbird.displayName ?? directory,
    category: manifest.mockingbird.category ?? "other",
    description: manifest.description ?? "",
    ...(manifest.mockingbird.vendor?.website
      ? { website: manifest.mockingbird.vendor.website }
      : {}),
    ...(manifest.mockingbird.vendor?.docs ? { docs: manifest.mockingbird.vendor.docs } : {}),
  })
}

const catalog = `// Generated by scripts/catalog.ts from packages/service/*/package.json. Do not edit.
export type CatalogEntry = {
  target: string
  package: string
  displayName: string
  category: string
  description: string
  website?: string
  docs?: string
}

export const CATALOG: readonly CatalogEntry[] = ${JSON.stringify(entries, null, 2)}

/** One lazy import per emulator, so a process only loads the emulators its fleets use. */
export const LOADERS: Record<string, () => Promise<{ serveTarget?: unknown }>> = {
${entries.map((entry) => `  ${JSON.stringify(entry.target)}: () => import("${entry.package}/server"),`).join("\n")}
}
`

const manifestPath = join(root, "package.json")
const manifest = (await Bun.file(manifestPath).json()) as {
  dependencies: Record<string, string>
}
const kept = Object.entries(manifest.dependencies).filter(
  ([name]) => !name.startsWith("@crvouga/mockingbird-service-"),
)
const dependencies = Object.fromEntries(
  [...kept, ...entries.map((entry) => [entry.package, "workspace:*"] as const)].sort(([a], [b]) =>
    a.localeCompare(b),
  ),
)
const nextManifest = `${JSON.stringify({ ...manifest, dependencies }, null, 2)}\n`

const outputs = [
  { path: join(root, "src/generated/catalog.ts"), text: catalog },
  { path: manifestPath, text: nextManifest },
]
let stale = false
for (const output of outputs) {
  const file = Bun.file(output.path)
  const current = (await file.exists()) ? await file.text() : ""
  if (current === output.text) continue
  if (check) {
    stale = true
    console.error(`stale: ${output.path} (run \`bun run generate\` in sites/fleet)`)
  } else await Bun.write(output.path, output.text)
}
if (stale) process.exit(1)
console.log(`catalog: ${entries.length} HTTP emulators`)
